<script>
/* A field that is not shown cannot be mandatory: untick and lock Mandatory when Show is unticked. */
document.querySelectorAll('[data-pagesetup] [data-show]').forEach(function(c){
  c.addEventListener('change',function(){var r=c.closest('tr').querySelector('[data-req]');if(!r)return;
    /* Remember Mandatory when Show is unticked and give it back when Show is ticked again (UX review S4). */
    if(!c.checked){r.dataset.was=r.checked?'1':'0';r.checked=false}else if(r.dataset.was==='1'){r.checked=true}
    r.disabled=!c.checked});
});
</script>
